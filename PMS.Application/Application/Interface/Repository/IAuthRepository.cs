using Microsoft.AspNetCore.Identity;
using PMS.Common.DTOs;
using PMS.Models.Models;

namespace PMS.Application.Application.Interface.Repository;

public interface IAuthRepository
{
    /// <summary>Registers a new user via ASP.NET Identity.</summary>
    Task<IdentityResult> RegisterAsync(SignupDto dto);

    /// <summary>Validates credentials and returns the Identity user if valid, null otherwise.</summary>
    Task<IdentityUser?> ValidateCredentialsAsync(LoginDto dto);

    /// <summary>Returns the roles assigned to the given user.</summary>
    Task<IList<string>> GetUserRolesAsync(IdentityUser user);

    /// <summary>Returns the FullName claim value stored for the given user.</summary>
    Task<string> GetFullNameAsync(IdentityUser user);

    /// <summary>
    /// Gets or creates the AppUser record (integer PK) linked to the given Identity user.
    /// Used to obtain the PharmacistId for sale creation.
    /// </summary>
    Task<User> GetOrCreateAppUserAsync(IdentityUser identityUser, string fullName);

    /// <summary>
    /// Assigns a single role to the given Identity user.
    /// The role must already exist (seeded at startup).
    /// </summary>
    Task<IdentityResult> AssignRoleAsync(IdentityUser user, string role);

    /// <summary>Finds an Identity user by their email address.</summary>
    Task<IdentityUser?> FindByEmailAsync(string email);

    /// <summary>Finds an Identity user by their unique ID (GUID string).</summary>
    Task<IdentityUser?> FindByIdAsync(string userId);

    /// <summary>
    /// Changes the password for an authenticated user.
    /// Validates the current password before applying the change.
    /// </summary>
    Task<IdentityResult> ChangePasswordAsync(IdentityUser user, string currentPassword, string newPassword);

    /// <summary>
    /// Generates a time-limited password reset token for the given user.
    /// The token should be delivered to the user via a secure out-of-band channel (e.g. email).
    /// </summary>
    Task<string> GeneratePasswordResetTokenAsync(IdentityUser user);

    /// <summary>
    /// Resets a user's password using the token generated by <see cref="GeneratePasswordResetTokenAsync"/>.
    /// The token is validated internally by ASP.NET Identity.
    /// </summary>
    Task<IdentityResult> ResetPasswordAsync(IdentityUser user, string token, string newPassword);

    /// <summary>
    /// Looks up the PharmacyProfile whose TenantId matches the given tenantId.
    /// Used by AuthService to embed the TenantId claim in the JWT.
    /// Returns null if no profile is found (unauthenticated/no tenant).
    /// </summary>
    Task<PharmacyProfile?> GetPharmacyProfileByTenantIdAsync(Guid tenantId);

    /// <summary>
    /// Looks up the first PharmacyProfile associated with the user's email.
    /// A user can belong to only one tenant in the current model.
    /// </summary>
    Task<PharmacyProfile?> GetPharmacyProfileByUserEmailAsync(string email);

    /// <summary>
    /// Creates a new PharmacyProfile (tenant root) and persists it.
    /// Called during tenant signup as part of the overall transaction.
    /// </summary>
    Task<PharmacyProfile> CreatePharmacyProfileAsync(string pharmacyName);

    /// <summary>
    /// Adds the "tenantId" claim to the given Identity user.
    /// Called after the PharmacyProfile is created during tenant signup.
    /// </summary>
    Task AddTenantClaimAsync(IdentityUser user, Guid tenantId);
}
